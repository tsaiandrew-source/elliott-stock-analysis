import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { normalizeTicker, readCoverageRegistry, validateCoverageRegistry, writeCoverageOrderBrowser } from './coverage-registry.mjs';
import { verifyMarketDataset } from './sync-market-data.mjs';

const contractHeader = '// Sanitized Universal Refresh contract; generated by scripts/sync-universal-refresh.mjs';
const sha256 = (value) => createHash('sha256').update(value).digest('hex');

export function pruneTicker(value, ticker) {
  const target = normalizeTicker(ticker);
  if (Array.isArray(value)) {
    return value
      .filter((item) => {
        if (!item || typeof item !== 'object') return true;
        return !['ticker', 'Ticker', 'symbol', 'Symbol'].some((key) => normalizeTicker(item[key]) === target);
      })
      .map((item) => pruneTicker(item, target));
  }
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.entries(value)
    .filter(([key]) => normalizeTicker(key) !== target)
    .map(([key, item]) => [key, pruneTicker(item, target)]));
}

export function parseContract(source) {
  const start = source.indexOf('{');
  const end = source.lastIndexOf('}');
  if (start < 0 || end < start) throw new Error('chart contract does not contain a JSON object');
  return JSON.parse(source.slice(start, end + 1));
}

export function renderContract(contract) {
  return `${contractHeader}\nwindow.PROTOTYPE_DATA_CONTRACT = ${JSON.stringify(contract, null, 2)};\n`;
}

async function writeJson(file, value) {
  await fs.writeFile(file, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

async function rebuildMarketManifest(repoRoot, registry) {
  const manifestPath = path.join(repoRoot, 'chart-surface/partial-market-data/MANIFEST.json');
  let previous = {};
  try { previous = JSON.parse(await fs.readFile(manifestPath, 'utf8')); } catch {}
  const tickers = {};
  for (const entry of registry.tickers) {
    const file = path.join(repoRoot, 'chart-surface/partial-market-data', `${entry.ticker}.json`);
    const contents = await fs.readFile(file, 'utf8');
    const dataset = verifyMarketDataset(JSON.parse(contents), { ticker: entry.ticker });
    tickers[entry.ticker] = {
      dataThrough: dataset.dataThrough,
      close: dataset.bars.at(-1).close,
      sha256: sha256(contents)
    };
  }
  await writeJson(manifestPath, {
    schemaVersion: 'elliott-completed-session-market-data-v1',
    sourceBatchId: previous.sourceBatchId || null,
    tickerOrder: registry.tickers.map((entry) => entry.ticker),
    tickers
  });
}

async function bumpPwaCache(repoRoot) {
  const file = path.join(repoRoot, 'service-worker.js');
  const source = await fs.readFile(file, 'utf8');
  const match = source.match(/const CACHE_VERSION = 'elliott-pwa-v(\d+)'/);
  if (!match) throw new Error('service-worker cache version marker is missing');
  const next = Number(match[1]) + 1;
  await fs.writeFile(file, source.replace(match[0], `const CACHE_VERSION = 'elliott-pwa-v${next}'`), 'utf8');
  return next;
}

function insertAfter(entries, entry, after) {
  if (!after) return [...entries, entry];
  const index = entries.findIndex((item) => item.ticker === normalizeTicker(after));
  if (index < 0) throw new Error(`--after ticker ${after} is not in the registry`);
  return [...entries.slice(0, index + 1), entry, ...entries.slice(index + 1)];
}

export async function planTickerLifecycle({ repoRoot, action, ticker, metadata = {}, marketDataPath = '', after = '', effectiveDate }) {
  const symbol = normalizeTicker(ticker);
  if (!/^[A-Z0-9.:-]+$/.test(symbol)) throw new Error('ticker is invalid');
  const registry = await readCoverageRegistry(repoRoot);
  const existing = registry.tickers.find((item) => item.ticker === symbol);
  if (action === 'remove') {
    if (!existing) throw new Error(`${symbol} is not in the canonical registry`);
    return {
      action, ticker: symbol, effectiveDate,
      registryBefore: registry.tickers.length,
      registryAfter: registry.tickers.length - 1,
      files: ['coverage-roster.json', 'coverage-order.js', 'chart-surface/data-contract.js', `chart-surface/partial-market-data/${symbol}.json`, 'chart-surface/partial-market-data/MANIFEST.json', 'service-worker.js']
    };
  }
  if (action !== 'add') throw new Error('action must be add or remove');
  if (existing) throw new Error(`${symbol} is already in the canonical registry`);
  for (const field of ['company', 'exchange', 'coverageGroup', 'marketGroup', 'marketSource']) {
    if (!String(metadata[field] || '').trim()) throw new Error(`--${field.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)} is required for add`);
  }
  if (!marketDataPath) throw new Error('--market-data is required for add');
  const dataset = verifyMarketDataset(JSON.parse(await fs.readFile(marketDataPath, 'utf8')), { ticker: symbol });
  const entry = {
    ticker: symbol,
    company: metadata.company,
    exchange: metadata.exchange.toUpperCase(),
    coverageGroup: metadata.coverageGroup,
    marketGroup: metadata.marketGroup,
    defaultView: metadata.defaultView || 'daily'
  };
  validateCoverageRegistry({ ...registry, updatedAt: effectiveDate, tickers: insertAfter(registry.tickers, entry, after) });
  return {
    action, ticker: symbol, effectiveDate,
    registryBefore: registry.tickers.length,
    registryAfter: registry.tickers.length + 1,
    dataThrough: dataset.dataThrough,
    files: ['coverage-roster.json', 'coverage-order.js', 'chart-surface/data-contract.js', `chart-surface/partial-market-data/${symbol}.json`, 'chart-surface/partial-market-data/MANIFEST.json', 'service-worker.js']
  };
}

export async function applyTickerLifecycle(options) {
  const { repoRoot, action, metadata = {}, marketDataPath = '', after = '', effectiveDate } = options;
  const ticker = normalizeTicker(options.ticker);
  const plan = await planTickerLifecycle(options);
  const registry = await readCoverageRegistry(repoRoot);
  const contractPath = path.join(repoRoot, 'chart-surface/data-contract.js');
  let contract = parseContract(await fs.readFile(contractPath, 'utf8'));
  if (action === 'remove') {
    registry.tickers = registry.tickers.filter((entry) => entry.ticker !== ticker);
    contract = pruneTicker(contract, ticker);
    await fs.rm(path.join(repoRoot, 'chart-surface/partial-market-data', `${ticker}.json`));
  } else {
    const source = await fs.readFile(marketDataPath, 'utf8');
    const dataset = verifyMarketDataset(JSON.parse(source), { ticker });
    const entry = {
      ticker,
      company: metadata.company,
      exchange: metadata.exchange.toUpperCase(),
      coverageGroup: metadata.coverageGroup,
      marketGroup: metadata.marketGroup,
      defaultView: metadata.defaultView || 'daily'
    };
    registry.tickers = insertAfter(registry.tickers, entry, after);
    contract.coverage = [...(contract.coverage || []), {
      ...entry,
      active: true,
      latestChartDate: dataset.dataThrough,
      marketSource: metadata.marketSource,
      chartSource: `partial-market-data/${ticker}.json`,
      gexSource: metadata.gexSource || '',
      freshness: `${dataset.dataThrough} · completed-session OHLCV`,
      optionsFreshness: '',
      analysisAvailable: false,
      intakeStatus: 'partial'
    }];
    await fs.writeFile(path.join(repoRoot, 'chart-surface/partial-market-data', `${ticker}.json`), `${JSON.stringify(dataset)}\n`, 'utf8');
  }
  registry.updatedAt = effectiveDate;
  validateCoverageRegistry(registry);
  await writeJson(path.join(repoRoot, 'coverage-roster.json'), registry);
  await writeCoverageOrderBrowser(repoRoot, registry);
  await fs.writeFile(contractPath, renderContract(contract), 'utf8');
  await rebuildMarketManifest(repoRoot, registry);
  const pwaCacheVersion = await bumpPwaCache(repoRoot);
  return { status:'APPLIED', ...plan, pwaCacheVersion };
}
